print("Приветствую Вас! Следуйте инструкциям для входа в систему.")

attempts = 4        # Задаём количество попыток ввода

while True:        # Запускаем цикл для ввода студенческого номера
    stud_num = input("Введите ваш студенческий номер: ")         # Вводим значение нашего номера и записываем его в переменную
    length = len(stud_num)        # Ставим переменную на длину нашего номера
    if length == 14:        # Если длина нашего номера не равно 14, значит номер неверный
        try:
            stud_num = int(stud_num)        # Для проверки введены цифры или нет
            break
        except ValueError:        # Если ошибка, то
            print("Введенный вами номер не является числом!") 
    else:        # Иначе принт с подсказкой
        print("Номер слишком короткий, он должен состоять из 14 цмфр.")   

stud_num = str(stud_num)        
stud_pass = stud_num[-4:] + "@AHUCM"        # Устанавливаем пароль из среза нашей переменной с номером и дополнением

while attempts != 0:        # Запускаем цикл 'Покс попытки не равны 0'
    password = input("Пожалуйста введите пароль (Подсказка: 4 последние цифры студенческого номера + @AHUCM): ")        # Ввод пароля
    if password != stud_pass:         # Проверяем наш пароль, если введенный не равен заданному
        attempts = attempts - 1        # При каждом неправильном вводе минусуем от попыток 1
        print(f"Пароль неправильный! Попыток: {attempts}")        # Напоминание об оставшихся попытках
        if attempts == 0:        # Если попыток 0, то цикл остановится самостоятельно 
            print("Вход запрещён!")
    else:        # Иначе вход  разрешен
        print("Вход разрешён!")
        break    